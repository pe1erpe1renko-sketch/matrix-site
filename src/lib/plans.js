/** Следующий тариф вверх — для допродажи и для окна «не хватает молний». */
export function nextPlanUp(plan) {
  const ladder = ['free', 'once', 'path', 'circle', 'pro'];
  const i = ladder.indexOf(plan);
  return i < 0 || i === ladder.length - 1 ? null : ladder[i + 1];
}

