/**
 * ЮРИДИЧЕСКИЕ ДОКУМЕНТЫ — ОДИН СПИСОК НА ВЕСЬ САЙТ
 * ================================================
 * Четыре документа показываются в трёх местах: колонка в подвале,
 * блок согласия при оформлении покупки и сами страницы /docs/…
 * Список лежит здесь, чтобы названия и адреса не разъехались:
 * добавили документ сюда — он сам появился везде.
 *
 * label — как называется в списке (подвал, страница документа)
 * short — как называется в строке согласия («Я принимаю оферту, …»),
 *         поэтому в винительном падеже и с маленькой буквы
 *
 * ТЕКСТЫ ДОКУМЕНТОВ ЗДЕСЬ НЕ ЛЕЖАТ. Их готовит юрист, вставлять их
 * нужно в src/pages/Docs.jsx — там помечено место.
 */
export const LEGAL_DOCS = [
  {
    id: 'terms',
    path: '/docs/terms',
    label: 'Пользовательское соглашение',
    short: 'пользовательское соглашение',
  },
  {
    id: 'privacy',
    path: '/docs/privacy',
    label: 'Политика обработки персональных данных',
    short: 'политику обработки персональных данных',
  },
  {
    id: 'consent',
    path: '/docs/consent',
    label: 'Согласие на обработку персональных данных',
    short: 'согласие на обработку персональных данных',
  },
  {
    id: 'offer',
    path: '/docs/offer',
    label: 'Публичная оферта',
    short: 'оферту',
  },
];

/** Документ по имени из адреса: 'terms' → объект или null. */
export function legalDoc(id) {
  return LEGAL_DOCS.find((d) => d.id === id) || null;
}

/** Ссылка на документ по имени — чтобы не писать адреса руками. */
export function legalPath(id) {
  const doc = legalDoc(id);
  return doc ? doc.path : '/';
}
