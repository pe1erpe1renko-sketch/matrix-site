/**
 * ЗАГЛУШКА ОТВЕТА НАСТАВНИКА
 * ==========================
 * Контекст для наставника собирает lib/prompts.js (buildMentorContext) —
 * он же уходит в системный промпт. Здесь остался только ответ-заглушка
 * для режима макета: нейросеть не подключена, а показать в переписке
 * что-то надо, и лучше показать настоящие числа человека, чем пустоту.
 *
 * Когда подключится провайдер (lib/chat.js), эта функция уходит.
 */

import { ARCANA_NAMES } from './prompts.js';

export function mentorPlaceholder(matrix, person, question) {
  const c = matrix.core;
  const t = matrix.today || {};
  const about = person && person.name ? `матрице (${person.name})` : 'вашей матрице';
  const named = (n) => `${n} (${ARCANA_NAMES[n]})`;

  return `Отвечаю по ${about}. Портрет личности — аркан ${c.W}, зона комфорта — ${c.C}, денежный канал — ${c.SE}, линия отношений — ${c.SW}.

Сейчас идёт период под арканом ${named(t.arcana)}, до смены примерно ${Math.max(0, Math.round((t.yearsToChange || 0) * 12))} мес. Аркан на сегодня — ${named(t.dayArcana)}.

Здесь будет живой разбор вашего вопроса «${question}» через эти числа. Сейчас включён режим макета: нейросеть не подключена (см. lib/chat.js), поэтому ответ собран по шаблону, но числа настоящие.`;
}
